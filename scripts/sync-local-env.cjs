const { execSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const envOutput = execSync("supabase status -o env", { encoding: "utf8" });
const vars = {};
for (const line of envOutput.split("\n")) {
  const match = line.match(/^([A-Z_]+)="(.*)"$/);
  if (match) vars[match[1]] = match[2];
}

const content = `# Auto-generated by scripts/sync-local-env.cjs — do not commit
NEXT_PUBLIC_SUPABASE_URL=${vars.API_URL || "http://127.0.0.1:56001"}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${vars.ANON_KEY || ""}
SUPABASE_SERVICE_ROLE_KEY=${vars.SERVICE_ROLE_KEY || ""}
DATABASE_URL=${vars.DB_URL || "postgresql://postgres:postgres@127.0.0.1:56002/postgres"}
NEXT_PUBLIC_APP_URL=http://localhost:3000
NEXT_PUBLIC_DEFAULT_LOCALE=en
NEXT_PUBLIC_DEFAULT_TIMEZONE=Asia/Riyadh
NEXT_PUBLIC_DEFAULT_CURRENCY=SAR
NEXT_PUBLIC_DEFAULT_FINANCIAL_YEAR_START_MONTH=1
`;

const target = path.join(process.cwd(), ".env.local");
fs.writeFileSync(target, content);
console.log("Wrote", target);
